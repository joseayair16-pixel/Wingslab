/** Devuelve el nombre del componente Lucide para cualquier valor guardado. */
export function resolveCategoryIcon(value?: string | null): string {
  if (!value) return 'UtensilsCrossed';
  const v = value.trim();
  if (!v) return 'UtensilsCrossed';
  if (v.startsWith('lucide:')) return v.slice(7);
  if (v.includes(':')) {
    const last = v.split(':').pop() || '';
    return FLUENT_TO_ICON[last] || CATEGORY_ICON_LIBRARY.find(i => i.label.toLowerCase() === last.replace(/-/g, ' '))?.icon || 'UtensilsCrossed';
  }
  if (LEGACY_LUCIDE_ICON[v]) return LEGACY_LUCIDE_ICON[v];
  if (EMOJI_TO_ICON[v]) return EMOJI_TO_ICON[v];
  return 'UtensilsCrossed';
}

export function filterCategoryIcons(query: string): CategoryIconOption[] {
  const q = query.trim().toLowerCase();
  if (!q) return CATEGORY_ICON_LIBRARY;
  return CATEGORY_ICON_LIBRARY.filter(i => i.label.toLowerCase().includes(q) || i.group.toLowerCase().includes(q));
}
