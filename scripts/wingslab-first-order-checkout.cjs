module.exports = async ({ state, save, evaluate, click, snapshot, sleep, assert, events }) => {
  assert(!state.orderBody, 'An order attempt already exists; inspect before retrying');
  await evaluate('customer', `document.querySelector('button[aria-label="Cerrar checkout"]')?.click()`);
  await evaluate('customer', `(()=>{const b=[...document.getElementById('wl_prod_alitas_6').querySelectorAll('button')].find(b=>b.innerText.trim()==='Agregar');if(b)b.click()})()`);
  await sleep(500);
  await evaluate('customer', `document.querySelector('button[aria-label="Abrir carrito"]')?.click()`);
  await sleep(700);
  await snapshot('customer', 'customer-cart');
  await click('customer', 'Completar pedido');
  await sleep(1800);
  await snapshot('customer', 'customer-checkout');
  assert(await evaluate('customer', `(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.innerText.includes('Instrucciones')&&b.innerText.includes('Opcional'));if(b)b.click();return !!b})()`));
  await sleep(400);
  await snapshot('customer', 'customer-instructions');
  assert(await evaluate('customer', `(()=>{const l=[...document.querySelectorAll('label')].find(l=>l.innerText.toLowerCase().includes('instrucciones para la tienda'));const e=l?.querySelector('input');if(!e)return false;Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(e,'WINGSLAB-E2E-01');e.dispatchEvent(new Event('input',{bubbles:true}));return true})()`));
  await sleep(200);
  assert(await evaluate('customer', `(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.innerText.trim().startsWith('Confirmar •'));if(b)b.click();return !!b})()`));
  await sleep(6500);
  const orders = await evaluate('customer', `(async()=>{const r=await fetch('/api/me/pedidos?page=1&limit=15',{headers:{Authorization:'Bearer '+localStorage.getItem('sadel.customer.token')}});const j=await r.json();return j.data.items.map(o=>({id:o.id,orderReference:o.orderReference,status:o.status}))})()`);
  assert.equal(orders.length,1,'Expected exactly one real new customer order');
  state.orderId=orders[0].id;state.folio=orders[0].orderReference;save('private-state.json',state);
  assert.equal(orders[0].status,'PENDING');
  await sleep(3000);
  assert(events.some(e=>e.role==='restaurant'&&e.event==='order:created'&&e.orderId===state.orderId),'Restaurant did not receive real order:created');
  await snapshot('customer','customer-pending');
  const panel = await snapshot('restaurant','restaurant-received');
  assert(panel.text.includes('Cliente Integral'),'New customer not visible in restaurant');
  save('creation-result.json',{order:orders[0],events});
  console.log('CREATED',JSON.stringify(orders[0]));
};
